/**
 * Generate 252 realistic daily OHLCV bars for any ticker
 */
export function generateSyntheticBars(ticker: string, basePrice: number = 200, count: number = 252): MarketBar[] {
  const bars: MarketBar[] = [];
  const now = new Date();
  let currentPrice = basePrice;

  for (let i = count; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    if (d.getDay() === 0 || d.getDay() === 6) continue;

    // Realistic daily return with gentle drift and standard market noise
    const dailyDrift = 0.0003;
    const shock = (Math.random() - 0.492) * 0.018;
    const returnPct = dailyDrift + shock;
    const prevClose = currentPrice;
    currentPrice = Math.max(1, Number((currentPrice * (1 + returnPct)).toFixed(2)));

    const intradaySpread = Math.max(0.004, Math.random() * 0.015);
    const high = Number((Math.max(prevClose, currentPrice) * (1 + intradaySpread)).toFixed(2));
    const low = Number((Math.min(prevClose, currentPrice) * (1 - intradaySpread)).toFixed(2));
    const open = Number((low + Math.random() * (high - low)).toFixed(2));
    const volume = Math.round(1500000 + Math.random() * 8000000);

    bars.push({
      date: d.toISOString().split("T")[0],
      open,
      high,
      low,
      close: currentPrice,
      volume,
      return: returnPct,
      drawdown: 0,
      volatility: 0.15,
      indicators: {
        sma_20: Number((currentPrice * 0.995).toFixed(2)),
        sma_50: Number((currentPrice * 0.985).toFixed(2)),
        rsi_14: Number((45 + Math.random() * 20).toFixed(1)),
        macd: Number(((currentPrice * 0.002)).toFixed(2)),
        macd_signal: Number(((currentPrice * 0.0018)).toFixed(2)),
        macd_hist: Number(((currentPrice * 0.0002)).toFixed(2)),
        bb_upper: Number((currentPrice * 1.035).toFixed(2)),
        bb_lower: Number((currentPrice * 0.965).toFixed(2)),
        atr_14: Number((currentPrice * 0.018).toFixed(2)),
      },
    });
  }
  return bars;
}

